-- 주문 통계 확인
SELECT 
    YEAR(order_date) as year,
    MONTH(order_date) as month,
    COUNT(*) as order_count,
    SUM(final_price) as total_revenue,
    AVG(final_price) as avg_order_value
FROM orders 
WHERE order_id BETWEEN 1000 AND 1104
GROUP BY YEAR(order_date), MONTH(order_date)
ORDER BY year, month;

-- 가격대별 주문 분포
SELECT 
    CASE 
        WHEN d.sale_price < 20000 THEN '2만원 미만'
        WHEN d.sale_price < 50000 THEN '2만원-5만원'
        WHEN d.sale_price < 100000 THEN '5만원-10만원'
        ELSE '10만원 이상'
    END as price_range,
    COUNT(*) as order_count,
    SUM(o.final_price) as total_revenue
FROM orders o
JOIN order_items oi ON o.order_id = oi.order_id
JOIN ddip_box d ON oi.product_id = d.ddipbox_id
WHERE o.order_id BETWEEN 1000 AND 1104
GROUP BY 
    CASE 
        WHEN d.sale_price < 20000 THEN '2만원 미만'
        WHEN d.sale_price < 50000 THEN '2만원-5만원'
        WHEN d.sale_price < 100000 THEN '5만원-10만원'
        ELSE '10만원 이상'
    END
ORDER BY MIN(d.sale_price);

-- 가장 많이 팔린 띱박스 아이템 TOP 10
SELECT 
    dbi.ddipbox_item_name,
    SUM(oi.quantity * dbi.item_quantity) as total_quantity_sold,
    COUNT(DISTINCT o.order_id) as order_count
FROM orders o
JOIN order_items oi ON o.order_id = oi.order_id
JOIN ddip_box_item dbi ON oi.product_id = dbi.ddipbox_id
WHERE o.order_id BETWEEN 1000 AND 1104
GROUP BY dbi.ddipbox_item_name
ORDER BY total_quantity_sold DESC
LIMIT 10;